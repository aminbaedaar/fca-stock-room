// Reads the weekly stock-report Excel and writes:
//   apps/web/src/demo/seed.json  - data for demo mode (no database needed)
//   supabase/seed.sql            - the same items + history for the real database
// Usage: node --experimental-strip-types scripts/make-seed.mjs <file.xlsx> [aligned|shiftLeft]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { importSheets } from '../packages/core/src/importer.ts';

const require = createRequire(new URL('../packages/core/package.json', import.meta.url));
const XLSX = require('xlsx');

const file = process.argv[2];
const alignment = process.argv[3] ?? 'aligned';
if (!file) {
  console.error('Usage: npm run seed -- <file.xlsx>');
  process.exit(1);
}

const wb = XLSX.read(readFileSync(file));
const sheets = wb.SheetNames.map((name) => ({
  name,
  rows: XLSX.utils.sheet_to_json(wb.Sheets[name], { header: 1, raw: true, defval: null }),
}));
const { items, dates } = importSheets(sheets, { alignment });

const seed = items.map((i, n) => ({
  name: i.name,
  size: i.size,
  category: i.category,
  unit: i.unit,
  qty: i.qty,
  min_level: i.min_level,
  note: i.note,
  sort: n + 1,
  counts: i.counts,
}));
mkdirSync(new URL('../apps/web/src/demo/', import.meta.url), { recursive: true });
writeFileSync(new URL('../apps/web/src/demo/seed.json', import.meta.url), JSON.stringify(seed, null, 1));

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sql = [
  '-- Generated by scripts/make-seed.mjs from ' + file.split('/').pop(),
  '-- Run once in the Supabase SQL editor on an empty database.',
  'begin;',
];
for (const i of seed) {
  sql.push(
    `with i as (insert into public.items (name, size, category, unit, qty, min_level, note, sort) values (${q(i.name)}, ${q(i.size)}, ${q(i.category)}, ${q(i.unit)}, ${i.qty}, ${i.min_level}, ${q(i.note)}, ${i.sort}) returning *),` +
      ` m as (insert into public.moves (id, type, item_id, item_name, unit, delta, balance, note) select gen_random_uuid(), 'created', id, public.fca_label(i), unit, qty, qty, 'Imported from Excel' from i)` +
      (i.counts.length
        ? ` insert into public.counts (item_id, date, qty) select i.id, c.date::date, c.qty from i, (values ${i.counts.map((c) => `(${q(c.date)}, ${c.qty})`).join(', ')}) as c(date, qty);`
        : ' select 1;'),
  );
}
sql.push('commit;', '');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql.join('\n'));

const warn = items.filter((i) => i.warnings.length);
console.log(`${items.length} items, ${dates.length} count dates (${dates[0]} to ${dates.at(-1)}).`);
for (const i of warn) console.log(`  ${i.name} ${i.size}: ${i.warnings.join('; ')}`);
